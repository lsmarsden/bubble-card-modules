import { load } from "js-yaml";
import type { BuiltModule } from "../build/buildModule";

/** The repository modules are released from. Screenshots are linked from its release tags. */
export const REPOSITORY = "lsmarsden/bubble-card-modules";

/** The store post's file name, in each module's dist/ folder and on each release. */
export const STORE_POST_FILE = "STORE_POST.md";

/** GitHub rejects a discussion body longer than this many characters. */
export const DISCUSSION_BODY_LIMIT = 65536;

/** Marks a post as generated, so a reader knows edits made on GitHub are overwritten by the next release. */
export const GENERATED_MARKER = "<!-- Generated by lsmarsden/bubble-card-modules.";

// Bubble Card's card ids and the names its store shows (getAvailableCardTypes in src/modules/module-editor.js).
// The store post contract test checks this list against the vendored copy.
export const CARD_NAMES: Record<string, string> = {
  button: "Button",
  calendar: "Calendar",
  climate: "Climate",
  cover: "Cover",
  "horizontal-buttons-stack": "Horizontal buttons stack",
  "media-player": "Media player",
  "pop-up": "Pop-up",
  select: "Select",
  separator: "Separator",
  "sub-buttons": "Sub-buttons",
};

/** The tag the release workflow creates for a module version. */
export function releaseTag(id: string, version: string): string {
  return `${id}/v${version}`;
}

/** An https URL for a file in a module folder at a release tag, so the post never shows a newer image. */
export function assetUrl(folder: string, tag: string, file: string): string {
  const encoded = [...tag.split("/"), "modules", folder, ...file.split("/")].map(encodeURIComponent).join("/");
  return `https://raw.githubusercontent.com/${REPOSITORY}/refs/tags/${encoded}`;
}

/**
 * Renders the GitHub discussion post that publishes a built module to Bubble Card's module store.
 *
 * The store reads the first ```yaml block (the module, installed exactly as written), takes its preview image from the
 * first https image, and shows the version and supported cards from the YAML. Everything else is for people reading
 * the discussion. Images point at the module's release tag, so render a version only once it has been released.
 *
 * @throws if a supported card id is unknown to Bubble Card, the YAML would break out of its code block, or the post
 *   is longer than GitHub allows.
 */
export function renderStorePost(built: BuiltModule): string {
  const { id, folder, info, yaml } = built;
  const tag = releaseTag(id, info.version);
  const [preview, ...more] = (info.screenshots ?? []).map((s) => `![${s.alt}](${assetUrl(folder, tag, s.file)})`);

  const unknown = info.supported.filter((card) => !CARD_NAMES[card]);
  if (unknown.length) throw new Error(`Module ${id}: Bubble Card has no card type ${unknown.join(", ")}`);
  if (yaml.includes("```")) throw new Error(`Module ${id}: the module YAML contains \`\`\`, which ends the code block`);

  const sections = [
    `# ${info.name}`,
    `**Version:** v${info.version}  \n**Creator:** [${info.creator}](https://github.com/${info.creator})`,
    ["> [!IMPORTANT]", "> **Supported cards:**", ...info.supported.map((card) => `>  - ${CARD_NAMES[card]}`)].join(
      "\n",
    ),
    preview,
    // Markdown ends an HTML block at a blank line and turns indented lines into code, so flatten the description.
    descriptionAsMarkdown(readDescription(yaml, id)),
    "---",
    [
      "<details>",
      "",
      "<summary><b>🧩 Get this Module</b></summary>",
      "",
      "<br>",
      "",
      `> To use this module, install **${info.name}** from the Module Store (in the editor of any card, open Modules), ` +
        `or copy and paste the following configuration into a \`/www/bubble/modules/${id}.yaml\` file.`,
      "",
      "```yaml",
      yaml.trimEnd(),
      "```",
      "",
      "</details>",
    ].join("\n"),
    more.length ? `---\n\n### More screenshots\n\n${more.join("\n\n")}` : undefined,
    `${GENERATED_MARKER} Released from modules/${folder} at ${tag}; edits made here are overwritten by the next release. -->`,
  ];
  const body = sections.filter(Boolean).join("\n\n") + "\n";

  if (body.length > DISCUSSION_BODY_LIMIT) {
    throw new Error(
      `Module ${id}: the store post is ${body.length} characters, over GitHub's ${DISCUSSION_BODY_LIMIT} limit`,
    );
  }
  return body;
}

function readDescription(yaml: string, id: string): string {
  const definition = (load(yaml) as Record<string, { description?: unknown }>)[id];
  return typeof definition?.description === "string" ? definition.description : "";
}

function descriptionAsMarkdown(description: string): string {
  return description
    .split("\n")
    .map((line) => line.trim())
    .filter(Boolean)
    .join("\n");
}
